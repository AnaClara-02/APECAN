CREATE TABLE usuarios (
    id_usuario BIGINT GENERATED BY DEFAULT AS IDENTITY,
    nome VARCHAR(150) NOT NULL,
    senha_hash VARCHAR(255) NOT NULL,
    login VARCHAR(50) NOT NULL,
    cpf CHAR(11) NOT NULL,
    email VARCHAR(254) NOT NULL,
    foto_url VARCHAR(500) NOT NULL,
    telefone VARCHAR(15) NOT NULL,
    tipo_de_perfil VARCHAR(20) NOT NULL,
    status VARCHAR(10) NOT NULL DEFAULT 'ATIVO',
    primeiro_acesso_pendente BOOLEAN NOT NULL DEFAULT TRUE,
    senha_definitiva_em TIMESTAMP,
    criado_por_usuario_id BIGINT,
    criado_em TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    atualizado_em TIMESTAMP,
    desativado_em TIMESTAMP,
    CONSTRAINT pk_usuarios PRIMARY KEY (id_usuario),
    CONSTRAINT uq_usuarios_login UNIQUE (login),
    CONSTRAINT uq_usuarios_cpf UNIQUE (cpf),
    CONSTRAINT uq_usuarios_email UNIQUE (email),
    CONSTRAINT fk_usuarios_criado_por FOREIGN KEY (criado_por_usuario_id)
        REFERENCES usuarios (id_usuario),
    CONSTRAINT ck_usuarios_cpf CHECK (cpf ~ '^[0-9]{11}$'),
    CONSTRAINT ck_usuarios_telefone CHECK (telefone ~ '^[0-9]{10,15}$'),
    CONSTRAINT ck_usuarios_tipo_de_perfil CHECK (
        tipo_de_perfil IN ('ADMINISTRADOR', 'USUARIO')
    ),
    CONSTRAINT ck_usuarios_status CHECK (status IN ('ATIVO', 'INATIVO')),
    CONSTRAINT ck_usuarios_desativacao CHECK (
        (status = 'ATIVO' AND desativado_em IS NULL)
        OR status = 'INATIVO'
    )
);

CREATE TABLE tokens_redefinicao_senha (
    id_token BIGINT GENERATED BY DEFAULT AS IDENTITY,
    id_usuario BIGINT NOT NULL,
    token_hash CHAR(64) NOT NULL,
    solicitado_em TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    expira_em TIMESTAMP NOT NULL,
    utilizado_em TIMESTAMP,
    CONSTRAINT pk_tokens_redefinicao_senha PRIMARY KEY (id_token),
    CONSTRAINT uq_tokens_redefinicao_senha_hash UNIQUE (token_hash),
    CONSTRAINT fk_tokens_redefinicao_usuario FOREIGN KEY (id_usuario)
        REFERENCES usuarios (id_usuario),
    CONSTRAINT ck_tokens_redefinicao_hash CHECK (token_hash ~ '^[0-9A-Fa-f]{64}$'),
    CONSTRAINT ck_tokens_redefinicao_expiracao CHECK (expira_em > solicitado_em),
    CONSTRAINT ck_tokens_redefinicao_utilizacao CHECK (
        utilizado_em IS NULL OR utilizado_em >= solicitado_em
    )
);

