CREATE VIEW vw_resumo_equipamentos_por_categoria AS
SELECT
    c.id_categoria,
    c.nome AS categoria,
    COUNT(e.id_equipamento) AS quantidade_total,
    COUNT(e.id_equipamento) FILTER (WHERE e.status = 'ATIVO') AS quantidade_ativa,
    COUNT(e.id_equipamento) FILTER (WHERE e.status = 'INATIVO') AS quantidade_inativa,
    COUNT(e.id_equipamento) FILTER (WHERE e.status = 'EMPRESTADO') AS quantidade_emprestada
FROM categorias_equipamentos c
LEFT JOIN equipamentos e ON e.id_categoria = c.id_categoria
GROUP BY c.id_categoria, c.nome;

